/**
 * Door color review. Prints which precedence layer supplied each door and
 * which doors the concurrence check flagged. Writes JSON and Markdown.
 *
 *   npx tsx scripts/door-color-review.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import catalog from "../shared/fixtures/doorStyleSideCatalog.json";
import { brandDoorSurfaceHex } from "../shared/shakerDoorBlueprint";
import {
  summarizeDoorColors,
  resolveDoorColor,
  type DoorColorInput,
} from "../shared/doorColorResolve";

const styles = catalog as DoorColorInput[];
const summary = summarizeDoorColors(styles);
const rows = styles.map((style) => {
  const decision = resolveDoorColor(style);
  return {
    id: style.id ?? null,
    name: style.ourName ?? style.aliasName ?? style.name ?? "",
    candidateSource: decision.candidateSource,
    candidateHex: decision.candidateHex,
    candidateCategory: decision.candidateCategory,
    appliedSource: decision.appliedSource,
    appliedHex: decision.appliedHex,
    appliedCategory: decision.appliedCategory,
    usesGrain: decision.usesGrain,
    pre209Hex: decision.pre209Hex,
    needsColorReview: decision.review.needsColorReview,
    keptBecause: decision.review.keptBecause,
    estimatorHex: decision.review.estimatorHex,
    estimatorSource: decision.review.estimatorSource,
    deltaE: decision.review.deltaE,
    hueChosen: decision.review.hueChosen,
    hueEstimator: decision.review.hueEstimator,
    swatch: decision.layers.swatch?.hex ?? null,
    walzcraft: decision.layers.walzcraft?.label ?? null,
    walzHex: decision.layers.walzcraft?.hex ?? null,
    acceptedRender: decision.layers.acceptedRender?.hex ?? null,
    brandSnapAvoided: brandDoorSurfaceHex(decision.candidateHex),
  };
});

const flagged = rows.filter((row) => row.needsColorReview);
const bySource = (key: "candidateSource" | "appliedSource") =>
  (["accepted-render", "render-hex", "catalog-color", "swatch-table", "walzcraft", "estimator", "pre-209"] as const)
    .map((source) => `| ${source} | ${rows.filter((row) => row[key] === source).length} |`)
    .join("\n");

const markdown = `# Door color review

Generated by \`scripts/door-color-review.ts\` from the ${summary.doors} styles in \`shared/fixtures/doorStyleSideCatalog.json\`.

The accepted render is the source of truth. No color is snapped to the brand list, and a nearest paint-chip match never paints a door. \`brandSnapAvoided\` is the old nearest swatch and is not painted.

## How concurrence works

After precedence picks a hex, an independent estimator (the color name, or the DL door-photo solid when the name is silent) compares it. They agree only when CIEDE2000 is at most 10, paint versus stain matches, and the hue family matches. A disagreement keeps the pre-209 color and sets \`needsColorReview\`. An accepted render, a hand-set render hex, and a saved catalog color are decisions and are kept, flagged rather than replaced. One opinion and no second method is applied as chosen.

## Coverage

Swatch table rows: ${summary.swatchTableRows} (cabinet-backend PR 72, \`data/door-colors/swatch-hex.json\`). A row marked \`demoted\` is a nearest paint-chip match, not a measurement of a door, and is never applied. Shaker Honey (330021) is demoted: \`#c8a040\` was the paint match, and the accepted render drives that door instead.
WalzCraft ColorPatterns rows: ${summary.walzRows}, of which ${summary.walzRowsWithHex} have a primary hex (\`data/door-colors/ColorPatterns_*.csv\`). A door with no accepted render, no render hex, and no saved color uses that shade. Rows with no primary hex do not count.

Layers present on a door (a lower layer can be present and still lose):

| layer | doors where that layer has a hex |
| --- | ---: |
| accepted render | ${summary.layerPresent["accepted-render"]} |
| render hex | ${summary.layerPresent["render-hex"]} |
| saved catalog color | ${summary.layerPresent["catalog-color"]} |
| swatch table (non-demoted) | ${summary.layerPresent["swatch-table"]} |
| WalzCraft | ${summary.layerPresent.walzcraft} |
| estimator | ${summary.layerPresent.estimator} |
| pre-209 | ${summary.layerPresent["pre-209"]} |

Candidate (highest layer that had a hex):

| source | doors |
| --- | ---: |
${bySource("candidateSource")}

Applied after concurrence:

| source | doors |
| --- | ---: |
${bySource("appliedSource")}

Agreed: ${summary.agreed}. Flagged: ${summary.flagged} (${summary.flaggedKeptPre209} kept the pre-209 color, ${summary.flaggedKeptRenderHex} kept a hand-set render hex or saved color, ${summary.flaggedKeptAcceptedRender} kept an accepted render). No second opinion: ${summary.noSecondOpinion}.

## Flagged doors

| id | name | chosen | from | applied | kept | estimator | deltaE |
| --- | --- | --- | --- | --- | --- | --- | --- |
${flagged.map((row) => `| ${row.id ?? ""} | ${row.name} | ${row.candidateHex} | ${row.candidateSource} | ${row.appliedHex} | ${row.keptBecause} | ${row.estimatorHex ?? ""} | ${row.deltaE == null ? "" : row.deltaE.toFixed(1)} |`).join("\n")}

## Every door

| id | name | candidate | applied | grain | review |
| --- | --- | --- | --- | --- | --- |
${rows.map((row) => `| ${row.id ?? ""} | ${row.name} | ${row.candidateSource} ${row.candidateHex} | ${row.appliedSource} ${row.appliedHex} | ${row.usesGrain ? "stain" : "paint"} | ${row.needsColorReview ? "flagged" : "ok"} |`).join("\n")}
`;

const outDir = resolve("docs/proofs");
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "door-color-review.json"), `${JSON.stringify({ summary, rows }, null, 2)}\n`);
writeFileSync(resolve(outDir, "door-color-review.md"), markdown);
console.log(JSON.stringify(summary, null, 2));
console.log(`flagged ${flagged.length}`);
console.log(`wrote ${resolve(outDir, "door-color-review.md")}`);
