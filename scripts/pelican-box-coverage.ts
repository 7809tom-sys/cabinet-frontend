/**
 * Pelican cabinet-box coverage report.
 *
 * Reads the catalog fixtures that the Designer's own tests use, classifies every
 * cabinet row with the same rules the Designer and the auto builder apply, and
 * writes docs/pelican-box-coverage.md. Fixtures only: this never touches the
 * production catalog, and it writes no database rows.
 *
 *   npx tsx scripts/pelican-box-coverage.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import realCatalog from "../client/src/lib/__fixtures__/autoDesignRealCatalog.json";
import matrixCatalog from "../client/src/lib/__fixtures__/autoDesignMatrixCatalog.json";
import ovenRows from "../client/src/lib/__fixtures__/ovenCabinetRows.json";
import type { DesignCabinet } from "../client/src/lib/design";
import {
  boxCoverageRow,
  isTallOvenPantryBox,
  summarizeBoxCoverage,
  type BoxCoverageRow,
} from "../client/src/lib/pelicanBoxCoverage";
import { displayTallSku } from "../client/src/lib/autoDesignTallCabinets";

type StylePack = { name?: string; base?: unknown[]; wall?: unknown[]; accessory?: unknown[]; surround?: unknown };
const real = realCatalog as unknown as Record<string, StylePack>;
const matrix = matrixCatalog as unknown as Record<string, StylePack>;
const tall = ovenRows as unknown as Array<DesignCabinet & { styleId: number }>;

const rows: BoxCoverageRow[] = [];
const styleNames: Record<string, string> = {};

function addStyle(styleId: string, pack: StylePack | undefined, fallbackName: string) {
  const label = pack?.name ?? fallbackName;
  styleNames[styleId] = label;
  for (const tag of ["base", "wall", "accessory"] as const) {
    for (const entry of (pack?.[tag] ?? []) as DesignCabinet[]) {
      if (!entry || typeof entry !== "object" || !entry.masterCode) continue;
      rows.push(boxCoverageRow(entry, styleId));
    }
  }
}

for (const [styleId, pack] of Object.entries(real)) addStyle(styleId, pack, `Line ${styleId}`);
for (const [styleId, pack] of Object.entries(matrix)) {
  if (styleNames[styleId]) continue;
  addStyle(styleId, pack, `Line ${styleId}`);
}
// Tall oven / pantry rows come from their own fixture because the real-catalog
// pull is base/wall/accessory only.
for (const entry of tall) {
  if (!entry?.masterCode) continue;
  rows.push(boxCoverageRow(entry as DesignCabinet, String(entry.styleId)));
  if (!styleNames[String(entry.styleId)]) styleNames[String(entry.styleId)] = `Line ${entry.styleId}`;
}

// One row per (style, SKU): a catalog can repeat a code across placements.
const deduped = new Map<string, BoxCoverageRow>();
for (const row of rows) {
  const key = `${row.style}|${row.masterCode}|${row.placement}`;
  if (!deduped.has(key)) deduped.set(key, row);
}
const summary = summarizeBoxCoverage(Array.from(deduped.values()));

const ovenPantries = summary.rows.filter((row) => normalized(row.masterCode).match(/^(UOC|O33|TOD|TOS)/) || /oven pantry|oven tower/i.test(row.description));

function normalized(code: string): string {
  return code.toUpperCase().replace(/[^A-Z0-9]/g, "");
}
function cell(value: string | number | null | undefined): string {
  const text = value == null ? "" : String(value);
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
function dims(row: BoxCoverageRow): string {
  const w = row.widthIn ?? "?";
  const h = row.heightIn ?? "?";
  const d = row.depthIn ?? "?";
  return `${w}″ × ${h}″ × ${d}″`;
}

const lines: string[] = [];
lines.push("# Pelican cabinet-box coverage");
lines.push("");
lines.push("Generated by `npx tsx scripts/pelican-box-coverage.ts` from the catalog fixtures the Designer's own tests use");
lines.push("(`client/src/lib/__fixtures__/autoDesignRealCatalog.json`, `autoDesignMatrixCatalog.json`, `ovenCabinetRows.json`).");
lines.push("It reads fixtures only: no production database rows are read or written.");
lines.push("");
lines.push("\"Available\" means both halves hold:");
lines.push("");
lines.push("1. the **auto builder / auto-designer** can place the box (a run piece, a measured anchor, a corner, or — for a tall oven/pantry — a pick from the tall pop-up), and");
lines.push("2. the **3D Designer** can draw it, which needs a real width, height, and depth plus a drawing rule.");
lines.push("");
lines.push("Roll-out trays, valances, moldings, panels, and fillers are **not boxes**. They stay add-on accessory lines, are");
lines.push("never auto-built as cabinet boxes, and are listed separately at the end.");
lines.push("");
lines.push("## Totals");
lines.push("");
lines.push("| Measure | Count |");
lines.push("| --- | --- |");
lines.push(`| Cabinet rows audited | ${summary.rows.length} |`);
lines.push(`| Available in the auto builder **and** 3D Designer | ${summary.available.length} |`);
lines.push(`| Missing | ${summary.missing.length} |`);
lines.push(`| Accessories (not boxes) | ${summary.accessories.length} |`);
lines.push("");
lines.push("## Oven pantry status");
lines.push("");
if (ovenPantries.length === 0) {
  lines.push("No oven pantry rows were found in the fixtures.");
} else {
  const available = ovenPantries.filter((row) => row.status === "available");
  lines.push(`${available.length} of ${ovenPantries.length} oven / pantry tall rows are available in both the auto-designer (tall pop-up) and the 3D Designer.`);
  lines.push("");
  lines.push("| SKU | Line | Size | Auto builder | 3D Designer | Status |");
  lines.push("| --- | --- | --- | --- | --- | --- |");
  for (const row of ovenPantries) {
    lines.push(`| ${cell(displayTallSku(row.masterCode))} | ${cell(styleNames[row.style] ?? row.style)} | ${dims(row)} | ${row.autoBuilder ? "yes" : "no"} | ${row.threeDDesigner ? "yes" : "no"} | ${row.status} |`);
  }
}
lines.push("");
lines.push("## Every cabinet box");
lines.push("");
lines.push("| SKU | Line | Placement | Size | Auto builder | 3D Designer | Status | Reason when missing |");
lines.push("| --- | --- | --- | --- | --- | --- | --- | --- |");
for (const row of summary.rows) {
  if (row.status === "accessory") continue;
  lines.push(`| ${cell(displayTallSku(row.masterCode))} | ${cell(styleNames[row.style] ?? row.style)} | ${cell(row.placement)} | ${dims(row)} | ${row.autoBuilder ? "yes" : "no"} | ${row.threeDDesigner ? "yes" : "no"} | ${row.status} | ${cell(row.reason ?? "")} |`);
}
lines.push("");
lines.push("## Missing boxes");
lines.push("");
if (summary.missing.length === 0) {
  lines.push("None: every cabinet row in the audited catalog renders in the 3D Designer and can be built.");
} else {
  lines.push("| SKU | Line | Placement | Size | Reason missing |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const row of summary.missing) {
    lines.push(`| ${cell(displayTallSku(row.masterCode))} | ${cell(styleNames[row.style] ?? row.style)} | ${cell(row.placement)} | ${dims(row)} | ${cell(row.reason ?? "")} |`);
  }
}
lines.push("");
lines.push("## Accessories, not boxes");
lines.push("");
lines.push("These are offered as add-on accessories on the plan. They are deliberately off the 3D Designer's cabinet-box path");
lines.push("and are never auto-built into a run.");
lines.push("");
lines.push("| SKU | Line | Sub-category | Size | Why it is not a box |");
lines.push("| --- | --- | --- | --- | --- |");
for (const row of summary.accessories) {
  lines.push(`| ${cell(displayTallSku(row.masterCode))} | ${cell(styleNames[row.style] ?? row.style)} | ${cell(row.subCategory)} | ${dims(row)} | ${cell(row.reason ?? "")} |`);
}
lines.push("");
lines.push("## How a box is decided");
lines.push("");
lines.push("- Auto-builder path: `client/src/lib/pelicanBoxCoverage.ts` (`autoBuilderPath`), which mirrors what `runAutoDesignLayout` seats.");
lines.push("- 3D Designer: `client/src/lib/pelicanBoxCoverage.ts` (`threeDDesignerCanDraw`) with the shared accessory split in `shared/designerEligibility.ts`.");
lines.push("- Tall oven/pantry auto-placement: `client/src/lib/autoDesignTallCabinets.ts`.");
lines.push("");

const out = resolve(import.meta.dirname, "../docs/pelican-box-coverage.md");
writeFileSync(out, `${lines.join("\n")}\n`, "utf8");
console.log(`Wrote ${out}`);
console.log(`rows=${summary.rows.length} available=${summary.available.length} missing=${summary.missing.length} accessories=${summary.accessories.length} ovenPantries=${ovenPantries.length}`);
void isTallOvenPantryBox;
