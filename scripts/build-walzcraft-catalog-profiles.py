#!/usr/bin/env python3
"""Generate shared/walzcraftCatalogProfiles.ts: verbatim rows of /workspace/walz/walzcraft_door_catalog.csv
for every WalzCraft style referenced by shared/walzcraftDistributorMatchesData.ts. No values are derived here."""
import csv, json, re, sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1] if len(sys.argv) > 1 else "/workspace/walz/walzcraft_door_catalog.csv")
data = (root / "shared/walzcraftDistributorMatchesData.ts").read_text()
codes = sorted(set(re.findall(r'"walzcraft": "(S\d+)\b', data)) | {"S592", "S109"})
rows = {}
for r in csv.DictReader(src.open()):
    m = re.match(r"(S\d+)\b", r["style"] or "")
    if m and m.group(1) in codes and m.group(1) not in rows:
        rows[m.group(1)] = {k: r[k] for k in ["style", "stile_rail_profile", "panel_profile", "frame_width", "panel_type", "bevel_reveal", "thickness", "finish", "color"]}
# Published widths only, each with a citation. Never guessed.
# 1) A stile/rail profile code that itself states the width, e.g. 'SR100 2 3/4"' or 'SR167 1 1/2"'.
# 2) S109: /workspace/walz/S109_reference_sheet.md (WalzCraft catalog V18.2 E.10.8 p.152, E.12.6 p.181).
S109_SHEET = {
    "frame_width": ('2-1/4"', 'S109_reference_sheet.md: stile/rail MP722-57 width 2-1/4" [57.0mm], WalzCraft catalog V18.2 E.10.8 (PDF p.152)'),
    "bevel_reveal": ('1"', 'S109_reference_sheet.md: panel PR317-25 reveal 1" [25mm], WalzCraft catalog V18.2 E.12.6 (PDF p.181)'),
    "thickness": ('3/4"', 'S109_reference_sheet.md: thickness 3/4" [19.1mm], product page + catalog E.10.8'),
}
for code, r in rows.items():
    src = {}
    for col in ("frame_width", "bevel_reveal", "thickness"):
        if r[col] and r[col] != "unknown":
            src[col] = f"walzcraft_door_catalog.csv {r['style']} · {col}"
    m = re.match(r'^(SR\d+)\s+(\d+(?:[ -]\d+/\d+)?")\s*$', r["stile_rail_profile"] or "")
    if r["frame_width"] == "unknown" and m:
        r["frame_width"] = m.group(2).replace("-", " ")
        src["frame_width"] = f'walzcraft_door_catalog.csv {r["style"]} · stile_rail_profile "{r["stile_rail_profile"]}" (width stated in the WalzCraft profile code)'
    if code == "S109":
        for col, (v, cite) in S109_SHEET.items():
            r[col] = v; src[col] = cite
    r["sources"] = src
out = ["// GENERATED by scripts/build-walzcraft-catalog-profiles.py from walzcraft_door_catalog.csv. Values are verbatim; frame_width/bevel_reveal/thickness may come from a cited published source (see sources); 'unknown' means not in WalzCraft data.",
       "export interface WalzCraftCatalogProfile { style: string; stile_rail_profile: string; panel_profile: string; frame_width: string; panel_type: string; bevel_reveal: string; thickness: string; finish: string; color: string; sources: Partial<Record<\"frame_width\" | \"bevel_reveal\" | \"thickness\", string>> }",
       "export const WALZCRAFT_CATALOG_PROFILES: Record<string, WalzCraftCatalogProfile> = " + json.dumps(rows, indent=2, ensure_ascii=False) + ";", ""]
(root / "shared/walzcraftCatalogProfiles.ts").write_text("\n".join(out))
print(len(rows), "of", len(codes), "codes:", [c for c in codes if c not in rows], "missing")
