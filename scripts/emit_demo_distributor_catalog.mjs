#!/usr/bin/env node
// Emits client/src/lib/demoDistributorCatalog.generated.ts for the demo
// distributor page (/distributor-preview).
//
// Source: the read-only live catalog snapshots already committed for the
// designer tests in client/src/lib/__fixtures__ (framed lines only), plus the
// Sinks & Faucets rows of the Pelican catalog snapshot. Codes are the USCD
// master codes exactly as the snapshots carry them; every code in the union is
// kept except rows marked as a checkout test item. Dimensions are copied.
// Prices are NOT copied for cabinets: the page applies demo placeholder prices.
//
// Run: node scripts/emit_demo_distributor_catalog.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fx = (name) => JSON.parse(readFileSync(join(root, "client/src/lib/__fixtures__", name), "utf8"));

const matrix = fx("autoDesignMatrixCatalog.json");
const real = fx("autoDesignRealCatalog.json");
// Framed line snapshots. Frameless (540xxx) snapshots use a different code set and are left out.
const SOURCES = [
  ["live390009.json", fx("live390009.json")],
  ["aeroSolsticeLive390019.json", fx("aeroSolsticeLive390019.json")],
  ["autoDesignMatrixCatalog.json#330014", matrix["330014"]],
  ["autoDesignMatrixCatalog.json#330020", matrix["330020"]],
  ["autoDesignMatrixCatalog.json#510004", matrix["510004"]],
  ["autoDesignMatrixCatalog.json#330002", matrix["330002"]],
  ["autoDesignRealCatalog.json#330011", real["330011"]],
];

const num = (v) => {
  const n = Number(v);
  return Number.isFinite(n) && n > 0 ? Number(n.toFixed(3)) : null;
};

const byCode = new Map();
const excluded = [];
for (const [, snap] of SOURCES) {
  for (const kind of ["base", "wall", "tall", "accessory"]) {
    for (const row of snap[kind] ?? []) {
      const code = String(row.masterCode ?? "").trim();
      if (!code || byCode.has(code)) continue;
      if (/checkout test/i.test(String(row.subCategory ?? ""))) {
        excluded.push(code);
        continue;
      }
      byCode.set(code, {
        code,
        description: String(row.description ?? code).trim(),
        kind,
        category: row.category ?? null,
        subCategory: row.subCategory ?? null,
        widthIn: num(row.width),
        heightIn: num(row.height),
        depthIn: num(row.depth),
      });
    }
  }
}
const cabinets = [...byCode.values()].sort((a, b) => a.code.localeCompare(b.code, "en", { numeric: true }));

const pelican = fx("pelicanCatalogRows.json")
  .filter((row) => row.category === "Sinks & Faucets")
  .map((row) => ({
    id: row.id,
    pelicanCode: row.pelicanCode ?? null,
    name: row.name,
    description: row.description ?? null,
    category: row.category,
    subCategory: row.subCategory ?? null,
    size: row.size ?? null,
    snapshotPrice: typeof row.sellPrice === "number" ? row.sellPrice : null,
  }));

const out = `// GENERATED by scripts/emit_demo_distributor_catalog.mjs. Do not edit by hand.
// Cabinet codes: union of the framed live-catalog snapshots in client/src/lib/__fixtures__
// (${SOURCES.map(([n]) => n).join(", ")}).
// Sinks & Faucets: client/src/lib/__fixtures__/pelicanCatalogRows.json.
// Excluded (checkout test items, not products): ${excluded.length ? excluded.join(", ") : "none"}.

export type DemoCatalogSourceRow = {
  code: string;
  description: string;
  kind: "base" | "wall" | "tall" | "accessory";
  category: string | null;
  subCategory: string | null;
  widthIn: number | null;
  heightIn: number | null;
  depthIn: number | null;
};

export type DemoFixtureSourceRow = {
  id: number;
  pelicanCode: string | null;
  name: string;
  description: string | null;
  category: string;
  subCategory: string | null;
  size: string | null;
  snapshotPrice: number | null;
};

export const DEMO_CATALOG_SOURCE_ROWS: DemoCatalogSourceRow[] = ${JSON.stringify(cabinets, null, 0).replace(/\},\{/g, "},\n  {")};

export const DEMO_FIXTURE_SOURCE_ROWS: DemoFixtureSourceRow[] = ${JSON.stringify(pelican, null, 0).replace(/\},\{/g, "},\n  {")};
`;
writeFileSync(join(root, "client/src/lib/demoDistributorCatalog.generated.ts"), out);
console.log(`cabinets ${cabinets.length}, sinks/faucets/accessories ${pelican.length}, excluded ${excluded.join(",") || "none"}`);
