import {
  cabinetWall, clampOpening, isSinkBaseCabinet, wallCeilingMin,
  type PlacedCabinet, type RoomData, type WallOpening,
} from "./design";

const COPY_TOLERANCE_IN = 0.25;

function near(left: number, right: number): boolean {
  return Math.abs(left - right) <= COPY_TOLERANCE_IN;
}

/**
 * A window Auto-Design created, or a shallow copy of one. A hand-placed window
 * has neither flag. The over-sink catalog label alone is not enough: the user
 * can place that same window by hand.
 */
export function isAutoGeneratedWindow(opening: WallOpening): boolean {
  return opening.kind === "window" && (opening.autoPlaced === true || Boolean(opening.faucetClearanceNote?.trim()));
}

function sameCopy(left: WallOpening, right: WallOpening): boolean {
  if (left.side === right.side) return false;
  if (!near(left.width, right.width) || !near(left.offset, right.offset)) return false;
  if (!near(left.height, right.height) || !near(left.sill, right.sill)) return false;
  const leftNote = left.faucetClearanceNote?.trim() ?? "";
  const rightNote = right.faucetClearanceNote?.trim() ?? "";
  if (left.autoPlaced && right.autoPlaced) return true;
  return leftNote.length > 0 && leftNote === rightNote;
}

/**
 * Saved plans can contain one Auto-Design window copied onto every wall.
 * Drop a window only when it is clearly machine-made and another copy with the
 * same width, offset, height, and sill already exists on a different wall.
 * Hand-placed windows are never removed. The copy that stays is the one on a
 * sink wall when the plan has a sink base, otherwise the first copy.
 */
export function dropDuplicateAutoWindows(
  openings: readonly WallOpening[],
  room: RoomData,
  placed: readonly PlacedCabinet[] = [],
): WallOpening[] {
  const auto = openings.filter(isAutoGeneratedWindow);
  if (auto.length < 2) return openings as WallOpening[];
  const sinkWalls = new Set(
    placed.filter((cabinet) => isSinkBaseCabinet(cabinet)).map((cabinet) => cabinetWall(cabinet, room)),
  );
  const drop = new Set<string>();
  const claimed = new Set<string>();
  for (const window of auto) {
    if (claimed.has(window.uid) || drop.has(window.uid)) continue;
    const copies = auto.filter((other) => other.uid === window.uid || sameCopy(window, other) || sameCopy(other, window));
    const sides = new Set(copies.map((copy) => copy.side));
    if (sides.size < 2) {
      copies.forEach((copy) => claimed.add(copy.uid));
      continue;
    }
    const keeper = copies.find((copy) => sinkWalls.has(copy.side)) ?? copies[0]!;
    for (const copy of copies) {
      claimed.add(copy.uid);
      if (copy.uid !== keeper.uid) drop.add(copy.uid);
    }
  }
  if (drop.size === 0) return openings as WallOpening[];
  return openings.filter((opening) => !drop.has(opening.uid));
}

/**
 * When a wall's top moves, every window on that wall moves by the same amount
 * and is then locked. Auto-Design will not shorten a locked window. The head
 * moves with the wall; the height stays unless the new wall is too short to
 * hold it, in which case the sill is clamped inside the wall.
 */
export function moveWindowsWithWallTops(
  openings: readonly WallOpening[],
  previousRoom: RoomData,
  nextRoom: RoomData,
): WallOpening[] {
  let changed = false;
  const next = openings.map((opening) => {
    if (opening.kind !== "window") return opening;
    const before = wallCeilingMin(previousRoom, opening.side);
    const after = wallCeilingMin(nextRoom, opening.side);
    const delta = Math.round((after - before) * 8) / 8;
    if (Math.abs(delta) < 0.01) return opening;
    changed = true;
    return clampOpening({
      ...opening,
      sill: opening.sill + delta,
      wallHeightLocked: true,
    }, nextRoom);
  });
  return changed ? next : openings as WallOpening[];
}
